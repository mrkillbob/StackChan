def frame(*,flags=0,changes=None):
    words=[0]*41;words[0]=91;words[1]=3;words[2]=123;words[3]=2;words[4]=3;words[7]=0xffffffff;words[25]=0xffffffff
    if changes:
        for index,value in changes.items():words[index]=value
    payload=struct.pack('>4sBBH41I',b'SCFD',1,flags,176,*words)
    return payload+struct.pack('>I',zlib.crc32(payload))
def mutate(wire,offset,data):
    result=bytearray(wire);result[offset:offset+len(data)]=data;result[-4:]=struct.pack('>I',zlib.crc32(result[:-4]));return bytes(result)
