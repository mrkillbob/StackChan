import Foundation
@main struct Checks {
 static func main() {
  func valid(_ s: String) -> Bool { PairingStatus.decode(Data(s.utf8)) != nil }
  assert(valid("{\"state\":\"paired\",\"acknowledged\":true,\"activity\":\"conversation\"}"))
  assert(valid("{\"state\":\"restoring\"}"))
  assert(valid("{\"state\":\"comparing\",\"code\":\"012345\"}"))
  assert(valid("{\"state\":\"paired\",\"acknowledged\":true}"))
  assert(!valid("{\"state\":\"paired\"}"))
  assert(!valid("{\"state\":\"comparing\",\"code\":\"12345\"}"))
  assert(!valid("{\"state\":\"comparing\",\"code\":\"１２３４５６\"}"))
  assert(!valid("{\"state\":\"paired\",\"code\":\"123456\",\"acknowledged\":true}"))
  assert(!valid("{\"state\":\"comparing\",\"credential\":\"synthetic-no-authority\"}"))
  assert(!valid("{\"state\":\"idle\",\"remaining\":true}"))
  assert(!valid("{\"state\":\"idle\",\"remaining\":120.5}"))
  assert(!valid("{\"state\":\"idle\",\"remaining\":121}"))
  assert(valid("{\"state\":\"idle\",\"remaining\":120}"))
  let cleanup = PairingStatus.decode(Data("{\"state\":\"failed\",\"message\":\"cleanup_unconfirmed\",\"cleanup\":[\"audio\",\"grant\",\"usb\"]}".utf8))
  assert(cleanup?.cleanupIssues == [.audio, .grant, .usb])
  assert(!valid("{\"state\":\"failed\",\"message\":\"cleanup_unconfirmed\"}"))
  assert(!valid("{\"state\":\"paired\",\"message\":\"cleanup_unconfirmed\",\"cleanup\":[\"audio\"]}"))
  assert(!valid("{\"state\":\"failed\",\"message\":\"cleanup_unconfirmed\",\"cleanup\":[\"usb\",\"usb\"]}"))
  assert(!valid("{\"state\":\"failed\",\"message\":\"cleanup_unconfirmed\",\"cleanup\":[\"secret\"]}"))
  assert(!valid("{\"state\":\"paired\",\"acknowledged\":1}"))
  assert(!valid("{\"state\":\"unknown\"}"))
  assert(!valid(String(repeating:" ",count:1025)))
  let active = PairingStatus.decode(Data("{\"state\":\"paired\",\"acknowledged\":true,\"activity\":\"conversation\",\"audio_remaining\":60}".utf8))
  assert(active?.activity == .conversation && active?.audioRemaining == 60)
  assert(!valid("{\"state\":\"paired\",\"acknowledged\":true,\"activity\":true}"))
  assert(!valid("{\"state\":\"paired\",\"acknowledged\":true,\"activity\":\"secret\"}"))
  assert(!valid("{\"state\":\"comparing\",\"activity\":\"conversation\"}"))
  assert(!valid("{\"state\":\"paired\",\"acknowledged\":true,\"activity\":\"physical_consent\",\"audio_remaining\":60}"))
  assert(!valid("{\"state\":\"paired\",\"acknowledged\":true,\"activity\":\"conversation\",\"audio_remaining\":61}"))
  assert(!valid("{\"state\":\"paired\",\"acknowledged\":true,\"activity\":\"conversation\",\"audio_remaining\":true}"))
  let generic=PairingStatus.decode(Data("{\"state\":\"failed\",\"message\":\"synthetic private exception\"}".utf8))
  assert(generic?.recovery == .setup && !generic!.recovery!.guidance.contains("private"))
  assert(PairingRecovery.project("certificate_expired") == .trustExpired)
  assert(PairingRecovery.project("audio_backpressure") == .audioBackpressure)
 print("PASS Companion/nativeUI status/cleanup-cause/secret-field/type/expiry checks; nohardwareIO")
 }
}
